import type { Transport } from "./transport";
import { ChainablePromise } from "./chainable";
import { DomainClientError } from "./domain-client-error";

const MUTATION_PREFIXES = [
  "create", "update", "delete", "add", "remove",
  "lock", "unlock", "reset",
];

function isMutation(name: string, explicitMutations?: ReadonlySet<string>): boolean {
  if (explicitMutations?.has(name)) return true;
  const lower = name.toLowerCase();
  return MUTATION_PREFIXES.some((p) => lower.startsWith(p));
}

function toGraphQLField(name: string): string {
  if (!name) return name;
  return name.charAt(0).toLowerCase() + name.slice(1);
}

export type GlobalErrorHandler = (error: DomainClientError) => void;

export interface ServiceProxyOptions {
  transport: Transport;
  sessionKey?: string | null;
  globalErrorHandler?: GlobalErrorHandler;
  /** V4.8.7: 用户级错误处理回调，由 DomainClientUser.handleError 提供。 */
  userErrorHandler?: (error: DomainClientError) => void;
  /** Map of GraphQL field names to their subfield selection strings.
   *  When provided, the proxy automatically appends `{ selection }` to each request.
   *  When omitted, the caller must provide `selection` directly in Transport.execute(). */
  selectionMap?: Record<string, string>;
  /** Mutation field names that don't match the prefix heuristic (e.g. "ping", "logout").
   *  When provided, these override the prefix-based detection. */
  explicitMutations?: ReadonlySet<string>;
  /** Map of GraphQL field names to their per-variable GraphQL type declarations.
   *  e.g. { rankings_Execute: { request: "GetRankingsReqDtoInput!" } }
   *  Generated by codegen（variableTypesMap，与 selectionMap 同源同代）。
   *  When provided, the proxy passes them through to Transport.execute().
   *  修订说明（Oracle S3）：variableTypes 覆盖主要用于与 selection 的对称性；
   *  变量类型由 schema 决定、由 codegen 产出，运行时逐调用覆盖非预期用法。 */
  variableTypesMap?: Record<string, Record<string, string>>;
}

export class ServiceProxy {
  private transport: Transport;
  private sessionKey?: string | null;
  private globalErrorHandler?: GlobalErrorHandler;
  private userErrorHandler?: (error: DomainClientError) => void;
  private selectionMap?: Record<string, string>;
  private explicitMutations?: ReadonlySet<string>;
  private variableTypesMap?: Record<string, Record<string, string>>;

  constructor(options: ServiceProxyOptions) {
    this.transport = options.transport;
    this.sessionKey = options.sessionKey;
    this.globalErrorHandler = options.globalErrorHandler;
    this.userErrorHandler = options.userErrorHandler;
    this.selectionMap = options.selectionMap;
    this.explicitMutations = options.explicitMutations;
    this.variableTypesMap = options.variableTypesMap;
  }

  createUse(): Record<string, (...args: unknown[]) => ChainablePromise<unknown>> {
    return new Proxy(
      {} as Record<string, (...args: unknown[]) => ChainablePromise<unknown>>,
      {
        get: (_target, prop: string | symbol) => {
          if (typeof prop !== "string") return undefined;
          return (...args: unknown[]) => {
            const field = toGraphQLField(prop);
            const type = isMutation(prop, this.explicitMutations) ? "mutation" as const : "query" as const;
            const variables = args[0] as Record<string, unknown> | undefined;
            // args[1] is an optional options bag with { signal?, selection?, variableTypes? }
            const options = args.length > 1 && typeof args[1] === "object" && args[1] !== null
              ? (args[1] as { signal?: AbortSignal; selection?: string; variableTypes?: Record<string, string> })
              : undefined;
            const sel = options?.selection ?? this.selectionMap?.[field];
            const variableTypes = options?.variableTypes ?? this.variableTypesMap?.[field];

            return new ChainablePromise(
              (resolve, reject) => {
                this.transport
                  .execute({
                    field,
                    type,
                    variables,
                    variableTypes,
                    selection: sel,
                    sessionKey: this.sessionKey ?? undefined,
                    signal: options?.signal,
                  })
                  .then((result) => {
                    // 解包 GraphQL `data` 字段键：execute() 返回 { [field]: 数据 }
                    // （GraphQL 标准 data 对象。GraphQLTransport.parseResponse 返回 json.data）。
                    // 消费端类型（生成代码 ChainablePromise<T>）声明为裸结果，此处还原为 T。
                    // 防御性 fallback：REST 平铺响应（无字段键）时原样透传。
                    const record = result as Record<string, unknown> | undefined;
                    const value = record?.[field];
                    resolve(value === undefined ? result : value);
                  })
                  .catch((error: unknown) => {
                    // V4.8.7: 先触发用户级错误处理
                    if (this.userErrorHandler && error instanceof DomainClientError) {
                      this.userErrorHandler(error);
                    }
                    reject(error);
                  });
              },
              this.globalErrorHandler,
            );
          };
        },
      },
    );
  }

  }
